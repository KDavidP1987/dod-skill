#!/usr/bin/env node
// dod-index.mjs — index and verify Definition-of-Done plans. No dependencies. Node 20+.
//
//   node dod-index.mjs [--dir <store>]        regenerate <store>/README.md, print a summary
//   node dod-index.mjs --list                 read-only listing of every plan (no write)
//   node dod-index.mjs --brief                one line for a session-start hook (never exits non-zero)
//   node dod-index.mjs --check <slug>         verify one plan's invariants; exit 1 on any violation
//   node dod-index.mjs --check-index          exit 1 if README.md is missing or stale
//   node dod-index.mjs --selftest             prove the checks block known-bad plans and pass a known-good one
//                                             (mutates DOD_TEST_SECRET for the process — run it in its own process,
//                                             as npm run validate and CI do; two selftests in one process race)
//
// Store resolution: --dir, else a `dod-store: <path>` line in ./CLAUDE.md, ./AGENTS.md or ./.cursor/rules/dod.mdc
// (conflicting declarations are an error), else docs/dod. Grammar is defined in ../references/plan-template.md.
// In grammar-controlled sections (Definition of Done, Baseline, Coverage, Assumptions, Amendments, Children, Log)
// a bullet or table row that does not match the grammar is a problem, not prose.

