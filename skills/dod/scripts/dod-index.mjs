export function parsePlan(text, file = "<memory>") {
  const plan = { file, slug: basename(file, ".md"), fm: {}, kind: "feature", sections: {}, headings: [], items: [], baseline: [], amendments: [], transitions: [], evidence: [], children: [], assumptions: [], coverage: [], gate: null, parseErrors: [], limitWarnings: [], reviews: [], versions: [], audits: [], proposed: [], notes: [], packages: [], steps: [], hasWbs: false };
  if (Buffer.byteLength(text) > LIMITS.bytes) plan.limitWarnings.push("plan exceeds 1 MB");
  // a line over the cap is reported and skipped — it is blanked so section boundaries and line numbers survive
  const lines = text.split(/\r?\n/).map((l, k) => { if (l.length <= LIMITS.line) return l; plan.limitWarnings.push(`line ${k + 1} is over 10,000 characters — skipped`); return ""; });
  let i = 0;
  if (lines[0] !== "---") { plan.parseErrors.push("no frontmatter"); return plan; }
  for (i = 1; i < lines.length && lines[i] !== "---"; i++) {
    const m = lines[i].match(/^([a-z_]+):\s*(.*)$/);
    if (m) plan.fm[m[1]] = m[2].trim();
    else if (lines[i].trim()) plan.parseErrors.push(`frontmatter line ${i + 1} is not key: value`);
  }
  if (i >= lines.length) { plan.parseErrors.push("frontmatter not closed"); return plan; }
  if (plan.fm.kind !== undefined) plan.kind = plan.fm.kind;
  let current = "";
  for (i = i + 1; i < lines.length; i++) {
    const line = lines[i];
    const h = line.match(/^(##+) (.+?)\s*$/);
    if (h) {
      const name = h[2].replace(/\s*·.*$/, "").replace(/\s*\(.*\)\s*$/, "").trim();
      plan.headings.push(name);
      if (h[1] === "##") { current = name; plan.sections[current] = plan.sections[current] ?? []; continue; }
    }
    if (current) plan.sections[current].push(line);
  }
  const sec = (name) => plan.sections[name] ?? [];
  const bad = (section, l) => plan.parseErrors.push(`${section}: line does not match the grammar: ${l.slice(0, 70)}`);
  // the title is a label: the Baseline comparison and the evidence rules see the line without it
  const item = (m) => { const t = splitTitle(m[3]); return { checked: m[1] !== " ", id: m[2], title: t.title, badTitle: t.bad, statement: t.statement, type: m[4], detail: m[5], line: `${m[2]} · ${t.statement} · ${m[4]}: ${m[5]}` }; };
  for (const l of sec("Definition of Done")) { const m = l.match(RE.item); if (m) plan.items.push(item(m)); else if (/^- /.test(l)) bad("Definition of Done", l); }
  for (const l of sec("Baseline")) { const m = l.match(RE.item); if (m) plan.baseline.push(item(m)); else if (/^- /.test(l)) bad("Baseline", l); }
  for (const l of sec("Amendments")) {
    const m = l.match(RE.amendment);
    if (m) plan.amendments.push({ id: m[1], n: Number(m[1].slice(1)), date: m[2], kind: m[3], ops: m[4].trim().split(/\s+/), layer: m[5].trim(), package: m[6] ?? null, why: m[7] });
    else if (/^- /.test(l)) bad("Amendments", l);
  }
  // the work breakdown: parents carry a title alone, leaves carry `items:` and `steps:` (D14). The section's
  // presence is itself a fact the checks turn on, so it is recorded even when the section holds no package line.
  plan.hasWbs = "Work breakdown" in plan.sections;
  for (const l of sec("Work breakdown")) {
    const m = l.match(RE.package);
    if (!m) { if (/^- /.test(l)) bad("Work breakdown", l); continue; }
    const leaf = m[3] !== undefined;
    if (leaf && !/^W\d+\.\d+$/.test(m[1])) { plan.parseErrors.push(`Work breakdown: ${m[1]} carries items and steps, so it is a leaf and needs a W<n>.<m> id: ${l.slice(0, 50)}`); continue; }
    plan.packages.push({ id: m[1], title: m[2], leaf, items: leaf ? m[3].split(" ") : [], steps: leaf ? m[4].split(",").map((s) => Number(s.trim())) : [] });
  }
  for (const l of sec("Build plan")) { const m = l.match(RE.step); if (m) plan.steps.push(Number(m[1])); }
  let seq = 0;
  for (const l of sec("Log")) {
    let m = l.match(RE.transition); if (m) { plan.transitions.push({ seq: seq++, date: m[1], status: m[2], detail: m[3] ?? "" }); continue; }
    m = l.match(RE.evidence); if (m) { plan.evidence.push({ seq: seq++, date: m[1], id: m[2], result: m[3], type: m[4], detail: m[5], commit: m[6].trim(), who: m[7].trim() }); continue; }
    m = l.match(RE.version); if (m) { plan.versions.push({ seq: seq++, date: m[1], label: m[2], text: (m[3] ?? "").trim() }); continue; }
    m = l.match(RE.audit); if (m) { plan.audits.push({ seq: seq++, date: m[1], runId: m[2], verified: Number(m[3]), total: Number(m[4]), stale: Number(m[5]), unaccounted: Number(m[6]) }); continue; }
    if (RE.auditStart.test(l)) { plan.parseErrors.push(`audit line does not match the grammar: ${l.slice(0, 70)}`); continue; }
    m = l.match(/^- (\d{4}-\d{2}-\d{2}) · note · (.+)$/); if (m) { plan.notes.push({ seq: seq++, date: m[1], text: m[2] }); continue; }
    if (/^- /.test(l) && !/^- \d{4}-\d{2}-\d{2} · (review skipped|renamed from|note) /.test(l)) bad("Log", l);
  }
  for (const l of sec("Children")) { const m = l.match(RE.child); if (m) plan.children.push({ slug: m[1], status: m[2], origin: m[3] ?? "baseline" }); else if (/^- /.test(l)) bad("Children", l); }
  for (const l of sec("Proposed")) {
    const m = l.match(RE.proposed);
    if (m) plan.proposed.push({ id: `P-${m[1]}`, target: m[2].trim(), change: m[3], why: m[4] }); else if (/^- /.test(l)) bad("Proposed", l);
  }
  for (const l of sec("Assumptions")) {
    const m = l.match(RE.assumption);
    if (!m) { if (/^- /.test(l)) bad("Assumptions", l); continue; }
    if (m[2] === "validated" && !/ · source: \S/.test(m[3])) bad("Assumptions", `${l}  (validated needs \` · source: <path / doc / who confirmed>\`)`);
    if (m[2] === "reversible" && !/ · fallback: \S/.test(m[3])) bad("Assumptions", `${l}  (reversible needs \` · fallback: <what changes if wrong>\`)`);
    plan.assumptions.push({ id: m[1], type: m[2] });
  }
  for (const l of sec("Coverage")) {
    const m = l.match(RE.coverage);
    if (m) { plan.coverage.push({ n: Number(m[1]), layer: m[2].trim(), status: m[3], probes: m[4].trim(), pointer: m[5].trim() }); continue; }
    const g = l.match(RE.gate); if (g) { plan.gate = g[1]; continue; }
    if (/^\|/.test(l) && !/^\| #/.test(l) && !/^\|-/.test(l)) bad("Coverage", l);
  }
  return plan;
}

export function parseReviews(text) {
  const reviews = [];
  let inDisp = false, block = null;
  for (const l of text.split(/\r?\n/)) {
    let m = l.match(RE.reviewHead);
    if (m) { reviews.push({ n: Number(m[1]), date: m[2], reviewer: m[3], verdict: null, findings: new Set(), dispositions: new Set(), rejected: new Set(), blocks: new Map(), earlier: null, coverage: null }); inDisp = false; block = null; continue; }
    if (!reviews.length) continue;
    const r = reviews.at(-1);
    if (/^### Dispositions/.test(l)) { inDisp = true; block = null; continue; }
    m = l.match(RE.verdict); if (m) { r.verdict = m[1]; block = null; continue; }
    m = l.match(RE.coverageLine); if (m) { r.coverage = l.trim(); block = null; continue; }
    if (inDisp) { m = l.match(RE.disposition); if (m) { r.dispositions.add(m[1]); if (m[2] === "rejected") r.rejected.add(m[1]); } continue; }
    if (/^EARLIER:/.test(l)) { r.earlier = l.trim(); block = null; continue; }
    // a finding's block runs from its Fn line to the line before the next finding, coverage or VERDICT line: what
    // the reviewer wrote about it, which D7 reads for gating-probe tokens
    m = l.match(RE.finding);
    if (m) { r.findings.add(m[1]); block = m[1]; r.blocks.set(block, l); continue; }
    if (block) r.blocks.set(block, `${r.blocks.get(block)}\n${l}`);
  }
  return reviews;
}

export function loadPlans(dir) {
  if (!existsSync(dir)) return [];
  const plans = readdirSync(dir)
    .filter((f) => f.endsWith(".md") && f !== "README.md" && f !== "profile.md" && !f.endsWith(".reviews.md"))
    .sort()
    .map((f) => [f, readFileSync(join(dir, f), "utf8")])
    // The "every node" discriminator (wbs-view D34): a plan is a `.md` that OPENS with a YAML front-matter
    // block. Filtering by file name alone is not enough, because `--export md` writes `wbs.md` into this same
    // store by default — and that export was then parsed as a plan and every line of it reported as a grammar
    // problem, so `dod list` showed phantom problems for a file this skill had just written itself. Skipped
    // silently rather than counted: Rollout 2 says no existing output gains a line.
    .filter(([, text]) => text.replace(/^﻿/, "").startsWith("---"))
    .map(([f, text]) => parsePlan(text, join(dir, f)));
  for (const p of plans) {
    const rf = join(dir, `${p.slug}.reviews.md`);
    p.reviews = existsSync(rf) ? parseReviews(readFileSync(rf, "utf8")) : [];
  }
  return plans;
}

