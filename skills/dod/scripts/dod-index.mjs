// the running version, or DOD_TEST_NODE_VERSION when it is older: the test hook can only add the refusal
const nodeRefusalVersion = (actual = process.versions.node) => { const t = process.env.DOD_TEST_NODE_VERSION; return !nodeSupported(actual) ? actual : t && !nodeSupported(t) ? t : null; };
export const nodeSupported = (version) => Number(String(version).replace(/^v/, "").split(".")[0]) >= 20;
// the plan file must be an entry directly inside the store, after both are realpath-resolved (a sibling
// `docs/dod-evil/x.md` shares the prefix `docs/dod` and is outside)
export const insideStore = (realStore, realFile) => { const r = relative(realStore, realFile); return !!r && !r.startsWith("..") && !r.includes(sep) && !r.includes("/") && resolve(realStore, r) === resolve(realFile); };
const localDate = (d = new Date()) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
const MIGRATED_RE = /^- \d{4}-\d{2}-\d{2} · note · migrated to dod 2/;

// Parse the --migrate command line from the arguments alone (refusal 0): exactly one slug, at most one --dry-run,
// at most one --to 1|2, at most one --dir <store>. Returns null on any malformed form.
export function parseMigrateArgs(args) {
  const out = { slug: null, to: 2, dryRun: false, dir: undefined };
  let seenTo = false, seenMigrate = false;
  for (let k = 0; k < args.length; k++) {
    const a = args[k];
    if (a === "--migrate") { if (seenMigrate) return null; seenMigrate = true; }
    else if (a === "--dry-run") { if (out.dryRun) return null; out.dryRun = true; }
    else if (a === "--to") { const v = args[++k]; if (seenTo || !["1", "2"].includes(v)) return null; seenTo = true; out.to = Number(v); }
    else if (a === "--dir") { const v = args[++k]; if (out.dir !== undefined || v === undefined || v.startsWith("--")) return null; out.dir = v; }
    else if (a.startsWith("--") || out.slug !== null) return null;
    else out.slug = a;
  }
  return seenMigrate && out.slug !== null ? out : null;
}

// The pure text change. to 2: `dod: 2`, whole-token A-n → S-n outside the frontmatter, Log and Baseline, the
// migration note appended after the Log's last non-empty line. to 1: the reverse rename, every `**title** ` prefix
// removed from current items and from Baseline lines (with S-n → A-n there too), and the latest migration note
// removed. Line endings are kept as they are.
export function migrateText(text, { to = 2, date = localDate() } = {}) {
  const eol = text.includes("\r\n") ? "\r" : "";
  const lines = text.split("\n");
  const changed = new Set();
  let renamed = 0, fm = 0, section = "", logEnd = -1;
  const from = to === 2 ? "A" : "S", into = to === 2 ? "S" : "A";
  const tokenRe = new RegExp(`(?<![\\w-])${from}-(\\d+)(?![\\w-])`, "g");
  for (let k = 0; k < lines.length; k++) {
    const l = lines[k].replace(/\r$/, "");
    if (fm < 2 && l === "---") { fm++; continue; }
    if (fm === 1) { if (/^dod:\s*/.test(l)) { lines[k] = `dod: ${to}${eol}`; changed.add(k); } continue; }
    const h = l.match(/^## (.+)$/);
    if (h) { section = h[1].trim(); continue; }
    if (section === "Log") { if (l.trim()) logEnd = k; continue; }
    if (section === "Baseline") {
      // to 1 only: a plan baselined at dod 2 carries titles and S-n in its Baseline; the older checker compares
      // whole lines, so they are converted too — the dod 2 comparison already reads both forms as the same line
      if (to === 1) {
        const next = outsideCode(lines[k], (part) => part.replace(tokenRe, (m, n) => `${into}-${n}`)).replace(/^(- \[[ x]\] D\d+ · )\*\*[^*]*\*\* /, "$1");
        if (next !== lines[k]) { lines[k] = next; changed.add(k); }
      }
      continue;
    }
    let next = outsideCode(lines[k], (part) => part.replace(tokenRe, (m, n) => { renamed++; return `${into}-${n}`; }));
    if (to === 1 && section === "Definition of Done") next = next.replace(/^(- \[[ x]\] D\d+ · )\*\*[^*]*\*\* /, "$1");
    if (next !== lines[k]) { lines[k] = next; changed.add(k); }
  }
  const added = [];
  if (to === 2) {
    const note = `- ${date} · note · ${MESSAGES_READABILITY.note}${eol}`;
    const at = logEnd >= 0 ? logEnd + 1 : lines.length;
    lines.splice(at, 0, note);
    added.push(at);
  } else {
    let latest = -1;
    section = "";
    lines.forEach((raw, k) => { const l = raw.replace(/\r$/, ""); const h = l.match(/^## (.+)$/); if (h) section = h[1].trim(); else if (section === "Log" && MIGRATED_RE.test(l)) latest = k; });
    if (latest >= 0) { lines.splice(latest, 1); for (const k of [...changed]) if (k > latest) { changed.delete(k); changed.add(k - 1); } }
  }
  const out = lines.join("\n");
  const shown = [...new Set([...changed, ...added])].sort((a, b) => a - b).map((k) => lines[k].replace(/\r$/, ""));
  return { text: out, lines: shown, renamed };
}

// Returns the exit code; prints change lines to stdout and a refusal (exactly one line) to stderr.
export function migratePlan(dir, slug, { to = 2, dryRun = false, nodeVersion = process.versions.node } = {}) {
  // one printed line per change (never wrapped: the change lines are the contract), sanitised like all plan text;
  // paths are shown relative to the working directory, so no output carries the home or temp directory
  const say = (l) => console.log(plainText(l));
  const shown = (x) => relative(process.cwd(), x).split(sep).join("/") || ".";
  const refuse = (key, vals) => { const v = { ...vals }; for (const k of ["path", "dir"]) if (v[k]) v[k] = shown(v[k]); console.error(plainText(fmtR(key, v))); return 1; };
  // (1) node-old — decided before any file or directory is read
  const old = nodeRefusalVersion(nodeVersion);
  if (old) return refuse("nodeOld", { version: old });
  // (2) bad-slug — no I/O
  if (!SLUG_RE.test(slug)) return refuse("noPlan", { slug, dir });
  // (2a) cannot-read the listing, (2b) no-plan
  let names;
  try { names = readdirSync(dir); } catch (e) { return refuse("cannotRead", { path: dir, code: e.code ?? "error" }); }
  if (!names.includes(`${slug}.md`)) return refuse("noPlan", { slug, dir });
  const file = join(dir, `${slug}.md`);
  // invalid UTF-8 is reported with the POSIX name for an illegal byte sequence, whatever the decoder calls it
  const read = () => { const b = readFileSync(file); try { return new TextDecoder("utf-8", { fatal: true }).decode(b); } catch { const e = new Error("invalid UTF-8"); e.code = "EILSEQ"; throw e; } };
  let text;
  try { text = read(); } catch (e) { return refuse("cannotRead", { path: file, code: e.code ?? (e instanceof TypeError ? "EILSEQ" : "error") }); }
  // (3) outside-store, (4) cannot-write (explicit, so a read-only file in a writable directory is refused here)
  let realStore, realFile;
  try { realStore = realpathSync(dir); realFile = realpathSync(file); } catch (e) { return refuse("cannotRead", { path: file, code: e.code ?? "error" }); }
  if (!insideStore(realStore, realFile)) return refuse("outside", { path: file });
  if (!dryRun) { try { accessSync(file, FS.W_OK); accessSync(dir, FS.W_OK); } catch (e) { return refuse("cannotWrite", { path: file, code: e.code ?? "error" }); } }
  for (let attempt = 0; attempt < 3; attempt++) {
    if (attempt) { try { text = read(); } catch (e) { return refuse("cannotRead", { path: file, code: e.code ?? "EILSEQ" }); } }
    const plans = loadPlans(dir);
    const parsed = parsePlan(text, file);
    parsed.reviews = plans.find((p) => p.slug === slug)?.reviews ?? [];
    const dodV = parsed.fm.dod ?? "1";
    // (5) already
    if (to === 2 && dodV === "2") return refuse("already", { slug, n: 2 });
    if (to === 1 && dodV !== "2") return refuse("already", { slug, n: 1 });
    // (6) s-collision — only a forward rename can collide
    if (to === 2) { const n = firstRenamedS(text); if (n !== null) return refuse("sCollision", { slug, n }); }
    // (7) check-problems, (8) untitled
    const others = plans.map((p) => (p.slug === slug ? parsed : p));
    if (checkPlan(parsed, others).problems.length) return refuse("checkProblems", { slug });
    if (to === 2) { const u = parsed.items.filter((x) => !x.title).map((x) => x.id); if (u.length) return refuse("untitledRefusal", { slug, ids: u.join(", ") }); }
    const r = migrateText(text, { to });
    // printed only once the file holds the result (or on a dry run), so a process that loses a race prints its one
    // refusal line and nothing else
    const report = () => { for (const l of r.lines) say(fmtR("change", { slug, line: l })); if (to === 2 && !r.renamed) say(fmtR("noAssumptions", { slug })); return 0; };
    if (dryRun) return report();
    let ok;
    try { ok = writeAtomic(file, r.text, { expect: text }); } catch (e) { return refuse("failed", { slug, code: e.code ?? "error" }); }
    if (ok) return report();
  }
  return refuse("changed", { slug });
}

// the first `S-<n>` token already in a section a forward migration renames (outside the frontmatter, Log and
// Baseline): after the rename it could not be told apart from a renamed A-n, so it is renamed by hand first
function firstRenamedS(text) {
  let fm = 0, section = "";
  for (const raw of text.split("\n")) {
    const l = raw.replace(/\r$/, "");
    if (fm < 2 && l === "---") { fm++; continue; }
    if (fm === 1) continue;
    const h = l.match(/^## (.+)$/);
    if (h) { section = h[1].trim(); continue; }
    if (section === "Log" || section === "Baseline") continue;
    let hit = null;
    outsideCode(l, (part) => { const m = part.match(/(?<![\w-])S-(\d+)(?![\w-])/); if (m && hit === null) hit = m[1]; return part; });
    if (hit !== null) return hit;
  }
  return null;
}

