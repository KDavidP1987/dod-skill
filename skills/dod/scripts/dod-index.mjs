// Printed text from a plan is untrusted: line separators become one space, then C0/C1 controls and Unicode format
// characters (bidi overrides, zero-width) are removed. Backups keep the line verbatim.
export const cleanLine = (v) => v.replace(/[\r\n\v\f\u0085\u2028\u2029]/g, " ").replace(/[\u0000-\u001F\u007F-\u009F\p{Cf}]/gu, "");
// Everything --check and --strip-v2 print: cleanLine, then any character outside printable ASCII and the four marks
// the output uses (`·` `→` `—` `✗`) is shown as <U+XXXX>, so no plan text can put an arbitrary glyph, a
// look-alike or a wide character on the terminal. Slugs are shown only when they match the slug grammar.
export const PLAIN_RE = /^[\x20-\x7e·→—✗…]*$/;
export const plainText = (v) => cleanLine(v).replace(/[^\x20-\x7e·→—✗…]/gu, (c) => `<U+${c.codePointAt(0).toString(16).toUpperCase().padStart(4, "0")}>`);
export const showSlug = (v) => (!/^[a-z0-9][a-z0-9-]*$/.test(v ?? "") ? "(invalid slug)" : v.length > 60 ? v.slice(0, 57) + "..." : v);
// Wrap one output line at ` · ` separators (then at spaces) so no line exceeds `width`; continuation lines are
// indented and each carries the same prefix, so every line stands on its own.
export function wrapLine(line, width = 120, prefix = "") {
  const out = [];
  let rest = line;
  // continuation lines carry four more spaces; every pass consumes at least one character, so a long prefix can
  // never stall the loop (the prefix itself is bounded: slugs print at most 60 characters, showSlug)
  const indent = () => (out.length ? 4 : 0);
  while (prefix.length + indent() + rest.length > width) {
    const room = Math.max(20, width - prefix.length - indent());
    let cut = rest.lastIndexOf(" · ", room);
    if (cut > 0) cut += 1; else cut = rest.lastIndexOf(" ", room);
    if (cut <= 0) cut = room;
    out.push(rest.slice(0, cut).trimEnd());
    rest = rest.slice(cut).trimStart();
  }
  out.push(rest);
  return out.map((l, k) => prefix + (k ? "    " : "") + l);
}

// The v0.1 shape of one plan: drops kind:, the Children origin field, version and audit Log lines and ## Proposed;
// sets parent: none when the parent is not an Epic and drops ## Children from a non-Epic. Returns the new text and
// every removed or changed line (original text), in file order.
// A rubric-2 Coverage row without its rubric-2 probe. A Considered row simply loses one probe from both sides. A
// Gap row's own list of open probes says whether the removed probe was answered: if the list names it, the probe was
// open (the answered count stays, the denominator drops, and a row with nothing left open becomes Considered); if it
// does not, the probe was answered and the answered count drops with the denominator.
export function stripCoverageRow(line) {
  const m = line.match(RE.coverage);
  if (!m) return null;
  const n = Number(m[1]);
  const probe = V2_PROBES[n];
  if (!probe) return null;
  const counts = m[4].trim().match(/^(\d+)\/(\d+)$/);
  if (!counts) return null; // an N/A row counts no probes
  let [, a, b] = counts.map(Number);
  let status = m[3], reason = m[5];
  if (status === "Gap") {
    const open = new RegExp(`(?<![\\w.])${probe.replace(".", "\\.")}(?![\\w.])`).test(reason);
    if (open) { reason = reason.replace(new RegExp(`\\s*${probe.replace(".", "\\.")}\\s*,?`), " ").replace(/\s*,\s*$/, "").replace(/\s{2,}/g, " "); b -= 1; }
    else { a -= 1; b -= 1; }
    // nothing open left: the row is Considered, and its reason is the pointer it kept
    if (a === b) status = "Considered";
  } else { a -= 1; b -= 1; }
  return `| ${m[1]} | ${m[2].trim()} | ${status} | ${a}/${b} | ${reason.trim()} |`;
}

export function stripPlanText(text, bySlug) {
  const lines = text.split("\n");
  const out = [], removed = [];
  let inFm = false, fmDone = false, section = "", dropSection = false, size = "";
  for (const m of text.matchAll(/^size:\s*(\S+)/gm)) { size = m[1]; break; }
  // plan-accuracy D15: a rubric-2 plan loses its rubric line, its four rubric-2 probes and the coverage_author
  // computed over them. The rows are rewritten first so the new line can be computed from them.
  const isV2 = /^rubric:\s*2\s*$/m.test(text);
  let authorLine = null;
  if (isV2) {
    const rows = [];
    for (const l of lines) {
      const m = l.replace(/\r$/, "").match(RE.coverage);
      if (!m) continue;
      const stripped = stripCoverageRow(l.replace(/\r$/, ""));
      const sm = (stripped ?? l.replace(/\r$/, "")).match(RE.coverage);
      rows.push({ n: Number(sm[1]), status: sm[3], probes: sm[4].trim() });
    }
    if (rows.length === LAYERS.length) authorLine = coverageLine(rows);
  }
  lines.forEach((raw, k) => {
    const l = raw.replace(/\r$/, "");
    if (!fmDone && k === 0 && l === "---") { inFm = true; out.push(raw); return; }
    if (inFm) {
      if (l === "---") { inFm = false; fmDone = true; out.push(raw); return; }
      if (/^kind:/.test(l)) { removed.push(raw); return; }
      if (isV2 && /^rubric:/.test(l)) { removed.push(raw); return; }
      if (isV2 && authorLine && /^coverage_author:/.test(l) && l.trim() !== `coverage_author: ${authorLine}`) { removed.push(raw); out.push(`coverage_author: ${authorLine}`); return; }
      const pm = l.match(/^parent:\s*(.*)$/);
      if (pm && pm[1].trim() !== "none" && bySlug.get(pm[1].trim())?.fm.size !== "Epic") { removed.push(raw); out.push(raw.replace(/^parent:.*?(\r?)$/, "parent: none$1")); return; }
      out.push(raw); return;
    }
    const h = l.match(/^## (.+?)\s*$/);
    if (h) {
      section = h[1].replace(/\s*·.*$/, "").replace(/\s*\(.*\)\s*$/, "").trim();
      dropSection = section === "Proposed" || (section === "Children" && size !== "Epic");
      if (dropSection) { removed.push(raw); return; }
      out.push(raw); return;
    }
    if (dropSection) { if (l.trim()) removed.push(raw); else out.push(raw); return; }
    if (section === "Log" && (RE.versionStart.test(l) || RE.auditStart.test(l))) { removed.push(raw); return; }
    // D22: the two kinds v0.1 does not know become the v0.1 kind with the same effect on the rate
    if (section === "Amendments") {
      const a = l.match(RE.amendment);
      if (a && V2_KINDS[a[3]]) { removed.push(raw); out.push(l.replace(` · ${a[3]} · `, ` · ${V2_KINDS[a[3]]} · `)); return; }
    }
    if (isV2 && section === "Coverage") {
      const row = stripCoverageRow(l);
      if (row && row !== l) { removed.push(raw); out.push(row); return; }
    }
    if (section === "Children") {
      const c = l.match(RE.child);
      if (c && c[3]) { removed.push(raw); out.push(raw.replace(/ · (?:baseline|A\d+)(\s*\r?)$/, "$1")); return; }
    }
    out.push(raw);
  });
  return { text: out.join("\n"), removed };
}

// --strip-v2 [--dry-run]: permission and containment are checked for every target before anything is written; per
// plan the backup (<store>/.strip-v2/<slug>.removed.md) is written first, then the plan with compare-before-rename.
// The backup is append-only: every strip that changes a plan appends the lines it removed, so an earlier strip's
// lines are never replaced — even when the same line is re-added and stripped again. The append uses
// compare-before-rename (three attempts, like every other write). A strip that then loses the race for the plan
// leaves its block in place: the backup may hold a block twice, never less — taking an append back could race a
// second strip's append and delete it.
function changedUnderneath() { const e = new Error("changed underneath"); e.code = "ECHANGED"; return e; }
function appendBackup(path, add) {
  for (let k = 0; k < 3; k++) {
    let cur = null;
    try { cur = readFileSync(path, "utf8"); } catch (e) { if (e.code !== "ENOENT") throw e; }
    const next = (cur ?? "") + add;
    if (process.env.DOD_FAULT === "backup-every-compare") appendFileSync(path, "- backup edited before the comparison\n"); // selftest only
    if (writeAtomic(path, next, { expect: cur, faults: false })) return;
  }
  throw changedUnderneath();
}

export function stripV2(dir, { dryRun = false } = {}) {
  const print = (slug, line) => { for (const l of wrapLine(plainText(line), 120, `strip ${showSlug(slug)}: `)) console.log(l); };
  const storeReal = realpathSync(dir);
  const inside = (p) => { const r = realpathSync(p); return r === storeReal || r.startsWith(storeReal + sep); };
  const backupDir = join(dir, ".strip-v2");
  // D15: v0.1 has no convergence rule, so a plan approved that way must get a READY review first. Checked before
  // anything is migrated or written, so a refused run leaves every plan as it was.
  for (const p of loadPlans(dir)) {
    if (!/ · converged$/.test(p.fm.review ?? "") && !convergedOnRecord(p)) continue;
    console.error(plainText(fmtA("stripConverged", { slug: showSlug(p.slug) })));
    return 1;
  }
  // dod 2 plans go back to dod 1 first (plan-readability D8): v0.1 knows neither titles nor S-n
  for (const p of loadPlans(dir)) if (p.fm.dod === "2" && migratePlan(dir, p.slug, { to: 1, dryRun })) return 1;
  const plans = loadPlans(dir);
  const { bySlug } = storeInfo(plans);
  const work = [];
  for (const p of plans) {
    const text = readFileSync(p.file, "utf8");
    const r = stripPlanText(text, bySlug);
    // orig: the bytes read (the compare target); text: the stripped result — spreading r over { text } overwrote the
    // original with the stripped text, so every first compare failed and only the retry wrote (found in code review 4)
    if (r.removed.length) work.push({ plan: p, orig: text, removed: r.removed, text: r.text });
  }
  if (!dryRun) {
    for (const w of work) if (!inside(w.plan.file)) { console.error(`refused: ${w.plan.file} resolves outside the store`); return 1; }
    if (existsSync(backupDir) && !inside(backupDir)) { console.error(`refused: ${backupDir} resolves outside the store`); return 1; }
    for (const target of [...work.map((w) => w.plan.file), existsSync(backupDir) ? backupDir : dir]) {
      try { accessSync(target, FS.W_OK); } catch (e) { console.error(`strip-v2: cannot write ${target} (${e.code ?? "error"})`); return 1; }
    }
  }
  for (const w of work) {
    const slug = w.plan.slug;
    for (const l of w.removed) print(slug, l);
    if (dryRun) continue;
    const backup = join(backupDir, `${slug}.removed.md`);
    let text = w.orig, r = w, done = false, backedUp = false;
    try {
      for (let attempt = 0; attempt < 3 && !done; attempt++) {
        if (attempt) { text = readFileSync(w.plan.file, "utf8"); r = stripPlanText(text, bySlug); if (!r.removed.length) { done = true; break; } }
        mkdirSync(backupDir, { recursive: true });
        appendBackup(backup, r.removed.join("\n") + "\n");
        backedUp = true;
        done = writeAtomic(w.plan.file, r.text, { expect: text });
      }
    } catch (e) {
      if (e.code === "ECHANGED") { console.error(`strip-v2: ${slug} changed underneath — not written`); return 1; }
      console.error(`strip-v2: ${slug} failed (${e.code ?? "error"}) — ${backedUp ? `backup kept at ${backup}` : "nothing written for it"}`);
      return 1;
    }
    if (!done) { console.error(`strip-v2: ${slug} changed underneath — not written`); return 1; }
  }
  return 0;
}

