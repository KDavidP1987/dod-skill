// A title is `**<title>** ` at the start of a statement: 1–40 code points, no `*`, no `·`, no line break, not blank.
export function splitTitle(statement) {
  if (!statement.startsWith("**")) return { title: null, statement, bad: false };
  const m = statement.match(/^\*\*([^*]*)\*\* (.+)$/);
  const t = m?.[1];
  if (!m || !t.trim() || Array.from(t).length > TITLE_MAX || /[·\r\n\u0085\u2028\u2029]/.test(t)) return { title: null, statement, bad: true };
  return { title: t, statement: m[2], bad: false };
}
