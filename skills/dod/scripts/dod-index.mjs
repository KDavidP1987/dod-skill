// The footer never carries an absolute path: it is the store's position relative to the working directory
// (`.` when they coincide), rendered with posix separators. A store on another root (drive letter, UNC share)
// has no relative position, so the footer carries no path at all. The one interpolated value passes through
// one escaping rule: backtick → ', control characters, line separators and Unicode format characters → space.
const ABS_START = /^(?:[A-Za-z]:[\\/]|[\\/])/;
const FOOTER_NO_PATH = "Store: outside the working directory (see the dod-store: line in your instructions file).";
function storeFooter(dir, opts = {}) {
  const rel = opts.relative ?? relative;
  const r = rel(opts.cwd ?? process.cwd(), dir);
  if (ABS_START.test(r)) return FOOTER_NO_PATH;
  const p = (r.split(sep).join("/") || ".").replace(/`/g, "'").replace(/[\u0000-\u001F\u007F-\u009F\u2028\u2029\p{Cf}]/gu, " ");
  return `Store: \`${p}\`.`;
}

// Names of the needles whose value occurs in text as a path of its own — an occurrence preceded by `.`, `/` or
// `\` continues a relative path (`../../tmp/x` legitimately contains `/tmp/x`) and is not a leak. Values, never
// names, are what must not leak, so callers report the names only.
export function scanForLeaks(text, needles) {
  const slashes = (t) => t.replace(/\\/g, "/"); // the footer renders posix separators, so a Windows needle must match in that form too
  const hay = slashes(text);
  const leaked = (v) => { for (let i = hay.indexOf(v); i !== -1; i = hay.indexOf(v, i + 1)) if (i === 0 || !"./".includes(hay[i - 1])) return true; return false; };
  return Object.entries(needles).filter(([, v]) => typeof v === "string" && v.length > 0 && leaked(slashes(v))).map(([k]) => k);
}

// Classify the store's existing README.md footer: "absolute" (written by dod ≤ 0.1.2, leaks the developer's
// filesystem layout), "oversize" (> 1 MB — not a generated index), "unreadable" (with the error code), or "ok"
// (relative, missing, or no footer line — freshness handles those). Bounded read from a descriptor, so a file
// that grows between stat and read is still capped; invalid UTF-8 decodes to U+FFFD and is judged as decoded.
const INDEX_CAP = 1024 * 1024;
export const fsio = { statSync, openSync, readSync, closeSync };
function legacyFooter(dir) {
  const f = join(dir, "README.md");
  let fd;
  try {
    const st = fsio.statSync(f, { throwIfNoEntry: false });
    if (!st) return { kind: "ok" };
    if (st.size > INDEX_CAP) return { kind: "oversize" };
    fd = fsio.openSync(f, "r");
    const buf = Buffer.alloc(INDEX_CAP + 1);
    let n = 0, got;
    while (n < buf.length && (got = fsio.readSync(fd, buf, n, buf.length - n, null)) > 0) n += got;
    if (n > INDEX_CAP) return { kind: "oversize" };
    const text = buf.subarray(0, n).toString("utf8").replace(/\r\n/g, "\n");
    const m = text.match(/^Store: `([^`\n]*)`/m);
    return { kind: m && ABS_START.test(m[1]) ? "absolute" : "ok" };
  } catch (e) {
    return { kind: "unreadable", code: e.code ?? "EIO" };
  } finally {
    if (fd !== undefined) { try { fsio.closeSync(fd); } catch { /* already closed */ } }
  }
}
