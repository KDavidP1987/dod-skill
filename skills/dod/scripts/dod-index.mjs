// Seed a random 24-char secret into the environment before any render, so the leak scan can prove that nothing
// the script writes carries an environment value. No entropy → one fixed line, exit 1, nothing created.
function seedSecret(rb = randomBytes) {
  const had = Object.prototype.hasOwnProperty.call(process.env, "DOD_TEST_SECRET");
  const previous = process.env.DOD_TEST_SECRET;
  const value = rb(18).toString("base64url");
  process.env.DOD_TEST_SECRET = value;
  return { value, restore() { if (had) process.env.DOD_TEST_SECRET = previous; else delete process.env.DOD_TEST_SECRET; } };
}

