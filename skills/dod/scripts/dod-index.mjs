export function coverageLine(rows) {
  const applicable = rows.filter((r) => r.status !== "N/A");
  const considered = applicable.filter((r) => r.status === "Considered");
  let pd = 0, pn = 0;
  for (const r of applicable) { const m = r.probes.match(/^(\d+)\/(\d+)$/); if (m) { pn += Number(m[1]); pd += Number(m[2]); } }
  return `${considered.length}/${applicable.length} layers · ${pn}/${pd} probes`;
}

// Store-wide facts computed once per loaded store (keyed by the plans array): the slug map and the parent cycles.
// Cycle detection is one three-colour walk over the parent edges — every plan is coloured once, so a 1,000-long
// chain costs O(n) in total, and checkPlan only looks its own answer up. Iterative: no recursion depth to overflow.
const STORE = new WeakMap();
export function storeInfo(all) {
  let info = STORE.get(all);
  if (info) return info;
  const bySlug = new Map();
  const byPlanId = new Map();
  for (const p of all) {
    if (!bySlug.has(p.slug)) bySlug.set(p.slug, p);
    if (p.fm.id) byPlanId.set(p.fm.id, [...(byPlanId.get(p.fm.id) ?? []), p]);
  }
  const colour = new Map(), cycles = new Map();
  for (const start of all) {
    if (colour.has(start.slug)) continue;
    const path = [];
    let cur = start;
    while (cur && !colour.has(cur.slug)) {
      colour.set(cur.slug, "grey"); path.push(cur.slug);
      const par = cur.fm.parent;
      cur = par && par !== "none" ? bySlug.get(par) : undefined;
    }
    if (cur && colour.get(cur.slug) === "grey") {
      const ring = path.slice(path.indexOf(cur.slug));
      ring.forEach((s, k) => { const rot = [...ring.slice(k), ...ring.slice(0, k)]; cycles.set(s, [...rot, s].join(" → ")); });
    }
    for (const s of path) colour.set(s, "black");
  }
  info = { bySlug, byPlanId, cycles, checking: new Set() };
  STORE.set(all, info);
  return info;
}

export function checkAll(plans) { return new Map(plans.map((p) => [p.slug, checkPlan(p, plans)])); }

// The work-package checks (wbs-view D15–D17). They all turn on the section being present: a plan without one is
// a plan that has not opted in, so none of them runs and `packagesSummary` says so rather than reading as a pass.
// The one thing an absent section can produce is `required` — a problem at rubric 2, the same words as a warning
// at rubric 1, and only for L and Epic (D16).
export function packageCheck(plan) {
  const problems = [], warnings = [];
  if (!plan.hasWbs) {
    if (["L", "Epic"].includes(plan.fm.size)) {
      const msg = fmtW("required", { size: plan.fm.size });
      if (rubricOf(plan) === 2) problems.push(msg); else warnings.push(msg);
    }
    // null, not [] — no section means no growth line at all, which is not the same as a section that grew nothing
    return { problems, warnings, grew: null };
  }
  const leaves = plan.packages.filter((p) => p.leaf);
  const ids = new Set(plan.items.map((i) => i.id));
  const steps = new Set(plan.steps);
  // every id a leaf names is resolved first, so a typo is reported as a typo rather than quietly moving an item
  // out of the ownership count below (D15)
  const owners = new Map();
  for (const p of leaves) {
    for (const id of p.items) {
      if (!ids.has(id)) { problems.push(fmtW("unknownId", { Wid: p.id, id })); continue; }
      owners.set(id, [...(owners.get(id) ?? []), p.id]);
    }
    for (const s of p.steps) if (!steps.has(s)) problems.push(fmtW("unknownId", { Wid: p.id, id: s }));
  }
  for (const i of plan.items) {
    const o = owners.get(i.id) ?? [];
    if (!o.length) problems.push(fmtW("ownedByNone", { Dn: i.id }));
    else if (o.length > 1) problems.push(fmtW("ownedByMany", { Dn: i.id, k: o.length, ids: o.join(", ") }));
  }
  for (const s of plan.steps) if (!leaves.some((p) => p.steps.includes(s))) problems.push(fmtW("stepNoPackage", { n: s }));
  // growth: only `+Dn` ops count, so a removal or a restatement never reads as growth (D17)
  const grewMap = new Map();
  for (const a of plan.amendments) {
    const adds = a.ops.filter((o) => /^\+D\d+$/.test(o));
    if (!adds.length) continue;
    if (!a.package) {
      if (a.kind === "discovered" || a.kind === "corrected") problems.push(fmtW("addsNoPackage", { An: a.id, Dn: adds[0].slice(1) }));
      continue;
    }
    // A2: the name has to resolve. Without this, a typo moved the growth off the package that really grew and
    // printed a row for one that does not exist — the same fault D15's fourth problem prevents in the other
    // direction — and the growth is dropped rather than misattributed, so no phantom row can reach the report.
    if (!leaves.some((p) => p.id === a.package)) { problems.push(fmtW("unknownPackage", { An: a.id, Wid: a.package })); continue; }
    grewMap.set(a.package, (grewMap.get(a.package) ?? 0) + adds.length);
  }
  const grew = [...grewMap].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).map(([id, n]) => ({ id, n }));
  return { problems, warnings, grew };
}

// What `--check` says it checked, so an absent section is never a silent pass (D14, D15, D17).
export const packagesSummary = (plan) => (!plan.hasWbs
  ? "packages none — no ## Work breakdown section, so ownership and growth are unchecked"
  : `packages ${plan.packages.length} (${plan.packages.filter((p) => p.leaf).length} leaf) · ownership and growth checked`);

export const grewLine = (grew) => `grew: ${grew.length ? grew.map((g) => `${g.id} +${g.n}`).join(" · ") : "none"}`;

// plan-accuracy A2: a plan approved on a converged review and re-reviewed READY later has no READY review dated on
// or before its baseline, and `review:` no longer says converged. The Log note D7 required is its approval record:
// a non-READY review dated on or before the baseline whose `converged after round n — k findings applied, none
// gating` note is dated between that review and the baseline. --check accepts it for the baseline date, and
// --strip-v2 refuses it exactly as it refuses a plan still marked converged (v0.1 has no such rule).
export function convergedOnRecord(plan) {
  const b = plan.fm.baselined;
  if (b === "none" || !validDate(b)) return false;
  if (plan.reviews.some((r) => r.verdict === "READY" && r.date <= b)) return false;
  return plan.reviews.some((r) => r.verdict !== "READY" && r.date <= b
    && plan.notes.some((x) => x.text === `converged after round ${r.n} — ${r.findings.size} findings applied, none gating` && x.date >= r.date && x.date <= b));
}

export function checkPlan(plan, all = [plan]) {
  const problems = [];
  const warnings = [...plan.limitWarnings];
  const fm = plan.fm;
  const status = fm.status;
  const past = PAST_DRAFT.includes(status);
  const store = storeInfo(all);
  if (plan.parseErrors.length) problems.push(...plan.parseErrors);
  if (fm.kind !== undefined && !KINDS.includes(fm.kind)) problems.push(`kind "${fm.kind}" must be feature, product or backlog`);
  if (plan.items.length > LIMITS.items) warnings.push("plan exceeds 500 items");
  // version lines: unique labels, non-decreasing dates, text required
  const labels = new Set();
  let lastVersion = "";
  for (const v of plan.versions) {
    if (labels.has(v.label)) problems.push(`version ${v.label} is already used`);
    labels.add(v.label);
    if (lastVersion && v.date < lastVersion) problems.push(`version ${v.label} dated before the previous version`);
    lastVersion = v.date; // compared with the line immediately before, so one out-of-order line is reported once
    if (!v.text) problems.push(`version ${v.label} has no text`);
  }
  for (const c of plan.children) if (c.origin !== "baseline" && !plan.amendments.some((a) => a.id === c.origin)) problems.push(`Children: origin ${c.origin} does not exist`);

  // 0. frontmatter
  for (const k of REQUIRED_FM) if (!(k in fm)) problems.push(`frontmatter is missing ${k}`);
  if (!STATUSES.includes(status)) problems.push(`status "${status}" is not one of ${STATUSES.join(", ")}`);
  if (fm.size && !SIZES.includes(fm.size)) problems.push(`size "${fm.size}" is not one of ${SIZES.join(", ")}`);
  if (fm.slug && fm.slug !== plan.slug) problems.push(`frontmatter slug "${fm.slug}" ≠ filename "${plan.slug}"`);
  if (fm.id && !/^dod-\d{8}-[a-z0-9]{4}$/.test(fm.id)) problems.push(`id "${fm.id}" is not dod-YYYYMMDD-xxxx`);
  if (fm.id) { const twin = (store.byPlanId.get(fm.id) ?? []).find((p) => p !== plan); if (twin) problems.push(`id ${fm.id} is also used by ${twin.slug} — ids are unique per store`); }
  for (const k of ["created", "baselined", "closed"]) if (fm[k] && fm[k] !== "none" && !validDate(fm[k])) problems.push(`${k} "${fm[k]}" is not a valid YYYY-MM-DD`);
  if (fm.created === "none") problems.push("created cannot be none");
  if (fm.coverage_author && fm.coverage_author !== "pending" && !RE.coverageLine.test(fm.coverage_author)) problems.push(`coverage_author "${fm.coverage_author}" is not "a/b layers · c/d probes"`);
  if (fm.coverage_reviewer && fm.coverage_reviewer !== "pending" && !RE.coverageLine.test(fm.coverage_reviewer)) problems.push(`coverage_reviewer "${fm.coverage_reviewer}" is not "a/b layers · c/d probes"`);
  const review = fm.review ?? "pending";
  // plan-accuracy D7: a plan may be approved on a converged review — three rounds, every finding applied, none gating
  const reviewM = review === "pending" ? null : review.match(/^(codex|subagent|human)(?: · (converged))?$/);
  if (review !== "pending" && !reviewM) problems.push(`review "${review}" must be pending, ${REVIEWERS.join(", ")}`);

  const ids = plan.items.map((x) => x.id);
  const dupes = ids.filter((x, k) => ids.indexOf(x) !== k);
  if (dupes.length) problems.push(`duplicate DoD ids: ${[...new Set(dupes)].join(", ")}`);
  const byId = new Map(plan.items.map((x) => [x.id, x]));
  // a message naming exactly one D-item names it `Dn (title)` when that current item is titled, else as v0.1 did
  const label = (id) => { const t = byId.get(id)?.title; return t ? `${id} (${cleanName(t)})` : id; };

  // 0a. format version, titles, assumption ids (plan-readability D1–D3)
  const dodV = fm.dod ?? "1";
  if (!["1", "2"].includes(dodV)) problems.push(fmtR("dodValue", { v: dodV }));
  for (const it of plan.items) if (it.badTitle) problems.push(fmtR("title", { n: it.id.slice(1) }));
  const untitled = plan.items.filter((x) => !x.title && !x.badTitle).map((x) => x.id);
  if (dodV === "2") for (const id of untitled) problems.push(fmtR("untitled", { n: id.slice(1) }));
  else if (untitled.length) warnings.push(fmtR("untitledWarn", { n: untitled.length, ids: untitled.join(", ") }));
  for (const a of plan.assumptions) {
    const n = a.id.slice(2);
    if (dodV === "2" && a.id.startsWith("A-")) problems.push(fmtR("assumptionA", { n }));
    if (dodV !== "2" && a.id.startsWith("S-")) problems.push(fmtR("assumptionS", { n }));
  }

  // plan-accuracy: which rubric scores this plan (absent → 1); an unknown value is a problem and scores as 1
  if (fm.rubric !== undefined && !RUBRICS.includes(String(fm.rubric))) problems.push(fmtA("rubricValue", { v: fm.rubric }));
  const rubric = rubricOf(plan);
  if (rubric === 1 && status === "draft") warnings.push(fmtA("rubricOneDraft"));
  const counts = probeCounts(rubric);
  const gating = gatingOf(rubric);

  // 1. coverage table: canonical rows, probe totals, pointers resolve, D-item mapping for 2–14; gate
  if (plan.coverage.length) {
    if (plan.coverage.length !== LAYERS.length) problems.push(`Coverage table has ${plan.coverage.length} rows, expected ${LAYERS.length}`);
    plan.coverage.forEach((r, k) => {
      const canon = LAYERS[k];
      if (!canon) return;
      const canonProbes = counts[k];
      if (r.n !== k + 1) problems.push(`Coverage row ${k + 1} is numbered ${r.n} — rows must be 1–15 in order`);
      if (r.layer !== canon) problems.push(`Coverage row ${k + 1} is "${r.layer}", expected "${canon}"`);
      if (r.status === "N/A") { if (r.pointer.length < 12) problems.push(`layer ${r.n} is N/A without an applicability test`); return; }
      const m = r.probes.match(/^(\d+)\/(\d+)$/);
      if (!m) problems.push(`layer ${r.n} probes "${r.probes}" is not n/n`);
      else {
        if (Number(m[2]) !== canonProbes) problems.push(`layer ${r.n} claims ${m[2]} probes; the rubric has ${canonProbes}${rubric === 2 ? ` (${probeIds(rubric, r.n).join(", ")})` : ""} — denominators are fixed; a probe you examined and found inapplicable is still answered (state the test in the section)`);
        if (Number(m[1]) > Number(m[2])) problems.push(`layer ${r.n} probes ${r.probes}: numerator exceeds denominator`);
        if (r.status === "Considered" && m[1] !== m[2]) problems.push(`layer ${r.n} is Considered with ${r.probes} probes — Considered means every applicable probe`);
        if (r.status === "Gap" && m[1] === m[2]) problems.push(`layer ${r.n} is Gap with all probes answered — mark it Considered or fix the count`);
      }
      if (r.status === "Considered") {
        const head = r.pointer.split("›")[0].trim().toLowerCase();
        if (!head) problems.push(`layer ${r.n} is Considered without a pointer`);
        else if (!plan.headings.some((h) => h.toLowerCase() === head || h.toLowerCase().startsWith(head))) problems.push(`layer ${r.n} pointer "${r.pointer.split("›")[0].trim()}" does not name a heading in this plan`);
        if (r.n >= 2 && r.n <= 14 && rubric === 2) {
          // pointer: <heading> [› <sub-heading>] › <probe> <Dn…>; <probe> prose: <reason>; …
          const segs = r.pointer.split("›");
          const body = segs.length > 1 ? segs[segs.length - 1] : "";
          const seen = new Map();
          for (const part of body.split(";").map((x) => x.trim()).filter(Boolean)) {
            const pm = part.match(/^(\d+\.\d+)\s+(.+)$/);
            if (!pm) continue;
            const [, probe, rest] = pm;
            if (!probeIds(rubric, r.n).includes(probe)) { problems.push(fmtA("probeForeign", { n: r.n, p: probe })); continue; }
            const prose = rest.match(/^prose:\s*(.*)$/);
            if (prose) {
              // a prose mapping the rubric refuses is still an attempt: it is reported once, with the reason,
              // and never again as unmapped
              seen.set(probe, true);
              if (gating.includes(probe)) problems.push(fmtA("probeProseGating", { n: r.n, p: probe }));
              else if (prose[1].trim().length < 12) problems.push(fmtA("probeProseShort", { n: r.n, p: probe }));
            } else if (/\bD\d+\b/.test(rest)) seen.set(probe, true);
          }
          for (const probe of probeIds(rubric, r.n)) if (!seen.has(probe)) problems.push(fmtA("probeUnmapped", { n: r.n, p: probe }));
        }
        if (r.n >= 2 && r.n <= 14) {
          const refs = [...r.pointer.matchAll(/\bD\d+\b/g)].map((x) => x[0]);
          if (!refs.length) problems.push(`layer ${r.n} is Considered but its pointer names no D-item (acceptance gate: every Considered layer 2–14 → ≥ 1 item, e.g. "Security › D4, D7")`);
          for (const d of refs) if (!byId.has(d)) problems.push(`layer ${r.n} pointer references ${d}, which is not a current item`);
        }
      }
    });
  }
  if (past) {
    if (!plan.coverage.length) problems.push(`status ${status} but no parseable Coverage table`);
    const gaps = plan.coverage.filter((r) => r.status === "Gap").map((r) => r.n);
    if (gaps.length) problems.push(`status ${status} with Gap layers: ${gaps.join(", ")}`);
    if (plan.gate !== "passed") problems.push(`status ${status} but the acceptance gate line is ${plan.gate ?? "missing"}`);
    if (plan.coverage.length === LAYERS.length && fm.coverage_author && fm.coverage_author !== coverageLine(plan.coverage)) problems.push(`coverage_author "${fm.coverage_author}" ≠ table "${coverageLine(plan.coverage)}"`);
    if (fm.coverage_reviewer === "pending") problems.push(`status ${status} but coverage_reviewer is pending`);
  }

  // 2. amendments: ids sequential, dates valid and nondecreasing, ops strict, IDs never reused
  const everSeen = new Set(plan.baseline.map((b) => b.id));
  const baseById = new Map(plan.baseline.map((b) => [b.id, b]));
  const expected = new Set(everSeen);
  const changedAt = new Map(); // id → date of last ~ or +
  let discoveredOps = 0, lastDate = "", lastN = 0;
  let lastMaterialReviewTrigger = null; // date of last amendment that requires re-review (gating probe or removal)
  for (const a of plan.amendments) {
    if (a.n !== lastN + 1) problems.push(`${a.id}: amendment ids must be sequential (expected A${lastN + 1})`);
    lastN = a.n;
    if (!validDate(a.date)) problems.push(`${a.id}: date "${a.date}" is not valid`);
    else if (a.date < lastDate) problems.push(`${a.id}: date ${a.date} is earlier than the previous amendment`);
    lastDate = a.date > lastDate ? a.date : lastDate;
    let designOps = 0, removal = false;
    if (!(a.ops.length === 1 && a.ops[0] === "—")) for (const tok of a.ops) {
      const m = tok.match(RE.op);
      if (!m) { problems.push(`${a.id}: op "${tok}" is not +Dn, -Dn, ~Dn or —`); continue; }
      const [, op, id] = m;
      if (op === "+") { if (everSeen.has(id)) problems.push(`${a.id}: +${id} but ${label(id)} was already used — IDs are never reused`); everSeen.add(id); expected.add(id); changedAt.set(id, a.date); designOps++; }
      else if (op === "-") { if (!expected.has(id)) problems.push(`${a.id}: -${id} but ${id} does not exist at that point`); expected.delete(id); removal = true; }
      else { if (!expected.has(id)) problems.push(`${a.id}: ~${id} but ${id} does not exist at that point`); changedAt.set(id, a.date); designOps++; }
    }
    if (a.kind === "discovered") { discoveredOps += Math.max(1, designOps); if (!/^\d{1,2}(\.\d)?$/.test(a.layer)) problems.push(`${a.id}: discovered amendments must name the layer or probe (e.g. 7 or 7.2), got "${a.layer}"`); }
    // plan-accuracy D20: a planning decision reversed counts exactly like discovered; a build finding nobody
    // could have foreseen is excluded, but must say what was found
    if (a.kind === "corrected") { discoveredOps += Math.max(1, designOps); if (!/^\d{1,2}(\.\d)?$/.test(a.layer)) problems.push(fmtA("correctedLayer", { An: a.id, layer: a.layer })); }
    if (a.kind === "emergent" && !/finding:\s*\S[\s\S]{11,}/.test(a.why)) problems.push(fmtA("emergentFinding", { An: a.id }));
    // D23: a scope change the user asked for should show up as a plan version
    if (rubric === 2 && a.kind === "requested" && !plan.versions.some((v) => v.date >= a.date)) warnings.push(fmtA("unversionedRequest", { An: a.id, date: a.date }));
    if (gating.includes(a.layer) || removal) lastMaterialReviewTrigger = a;
  }
  // plan-accuracy D6: an item named by ACCRETION or more amendments, counting each amendment once
  for (const it of plan.items) {
    const k = plan.amendments.filter((a) => a.ops.some((tok) => tok.slice(1) === it.id)).length;
    if (k >= ACCRETION) warnings.push(fmtA("accretion", { n: it.id.slice(1), k }));
  }

  // plan-accuracy D4: under rubric 2 a test or cmd item says what makes it fail. `## Baseline` is history, so it
  // is never checked; `file` and `manual` items have no failing input to name.
  if (rubric === 2) for (const it of plan.items) {
    if (it.type !== "test" && it.type !== "cmd") continue;
    const m = it.detail.match(/fails when:([\s\S]*)$/);
    if (!m || m[1].replace(/\s/g, "").length < 3) problems.push(fmtA("failsWhen", { n: it.id.slice(1) }));
  }

  // plan-accuracy D5: prose that claims a control — "uploads are validated" — with no D-item behind it is a
  // warning, never a problem: the reviewer decides whether the claim is carried by an item.
  if (rubric === 2) {
    let over = 0;
    const hits = [];
    for (const name of PROSE_SECTIONS) {
      for (const raw of plan.sections[name] ?? []) {
        if (/^\s*#/.test(raw)) continue; // a sub-heading is a label, not a claim
        // a claim inside a code span is a symbol, not prose
        const line = raw.replace(/`[^`]*`/g, " ");
        for (const sentence of line.split(/(?<=[.!?])\s+/)) {
          if (!CONTROL_RE.test(sentence) || /\bD\d+\b/.test(sentence)) continue;
          if (hits.length < PROSE_CAP) hits.push(fmtA("proseControl", { text: cleanLine(sentence.trim()).slice(0, 60), section: name }));
          else over++;
        }
      }
    }
    warnings.push(...hits);
    if (over) warnings.push(fmtA("proseMore", { k: over }));
  }

  if (past) {
    if (!plan.baseline.length) problems.push(`status ${status} but ## Baseline is empty`);
    else {
      const cur = new Set(ids);
      const missing = [...expected].filter((x) => !cur.has(x));
      const extra = [...cur].filter((x) => !expected.has(x));
      if (missing.length || extra.length) problems.push(`amendment drift — current DoD ≠ baseline + amendments (missing: ${missing.join(", ") || "none"}; unexplained: ${extra.join(", ") || "none"})`);
      for (const it of plan.items) {
        const b = baseById.get(it.id);
        if (b && !changedAt.has(it.id) && sameIds(b.line) !== sameIds(it.line)) problems.push(`${label(it.id)} differs from ## Baseline without a ~${it.id} amendment`);
      }
    }
  }

  // 3. evidence: type matches; pass after last fail (Log order) and on/after the item's last amendment
  const verified = new Set(), preVerified = new Set();
  const readySeq = plan.transitions.find((t) => t.status === "ready")?.seq;
  for (const e of plan.evidence) {
    if (!validDate(e.date)) problems.push(`evidence for ${label(e.id)}: date "${e.date}" is not valid`);
    const it = byId.get(e.id);
    if (!it) { warnings.push(`evidence for ${e.id}, which is not a current item`); continue; }
    if (e.type !== it.type) problems.push(`${label(e.id)} evidence type "${e.type}" ≠ item type "${it.type}"`);
  }
  for (const it of plan.items) {
    const ev = plan.evidence.filter((e) => e.id === it.id);
    const lastFail = ev.filter((e) => e.result === "fail").at(-1);
    const since = changedAt.get(it.id) ?? "";
    const passes = ev.filter((e) => e.result === "pass" && e.type === it.type && (!lastFail || e.seq > lastFail.seq) && e.date >= since);
    const pass = passes.at(-1);
    if (pass) verified.add(it.id);
    // evidence recorded before the plan reached ready (Log order decides, not the date): a backlog plan counts it as
    // pre-verified — the slice already worked in the existing system; any other kind is warned about. Any such pass
    // counts, even when a later pass exists too.
    const early = passes.some((e) => readySeq === undefined || e.seq < readySeq);
    if (early && plan.kind === "backlog") preVerified.add(it.id);
    else if (early) warnings.push(`evidence before baseline: ${label(it.id)} passed before the plan reached ready`);
    if (it.checked && !pass) problems.push(`${label(it.id)} is checked without evidence (no pass after the last fail${since ? ` and after its amendment on ${since}` : ""})`);
  }

  // 4. review: reviews file, READY on record with findings dispositioned, re-review after gating / removal amendments
  const readyReviews = plan.reviews.filter((r) => r.verdict === "READY");
  for (const r of plan.reviews) {
    if (!validDate(r.date)) problems.push(`Review ${r.n}: date "${r.date}" is not valid`);
    if (!r.verdict) problems.push(`Review ${r.n} has no VERDICT line`);
    const undisposed = [...r.findings].filter((f) => !r.dispositions.has(f));
    if (undisposed.length) problems.push(`Review ${r.n}: findings without a disposition: F${undisposed.join(", F")}`);
    if (r.verdict === "READY" && !r.coverage) problems.push(`Review ${r.n} is READY but has no reviewer coverage line`);
  }
  plan.reviews.forEach((r, k) => {
    if (r.n !== k + 1) problems.push(`Review ${r.n}: reviews must be numbered sequentially (expected Review ${k + 1})`);
    if (k && r.date < plan.reviews[k - 1].date) problems.push(`Review ${r.n} is dated before Review ${plan.reviews[k - 1].n}`);
  });
  const lastReview = plan.reviews.at(-1);
  const lastReady = readyReviews.at(-1);
  // plan-accuracy D7: a round-3-or-later review whose findings were all applied and none of them gating stands in
  // for a READY verdict. Every condition it fails is its own problem, so the author sees all of them at once. A
  // converged marker over a latest READY review is just that review — the conditions below do not apply.
  let converged = null;
  // when a converged review is on offer, its conditions are the verdict: the author is told which one failed,
  // not that the file has no READY line
  const convAttempted = reviewM?.[2] === "converged" && lastReview && lastReview.verdict !== "READY";
  if (convAttempted) {
    const v = review, n = lastReview.n, k = lastReview.findings.size;
    const before = problems.length;
    if (n < 3) problems.push(fmtA("convergedRound", { v, n }));
    if (lastReview.coverage !== fm.coverage_reviewer) problems.push(fmtA("convergedCoverage", { v, n, c: lastReview.coverage ?? "none", cr: fm.coverage_reviewer ?? "none" }));
    if (lastReview.earlier !== "EARLIER: all resolved") problems.push(fmtA("convergedEarlier", { v, n }));
    for (const f of lastReview.rejected) problems.push(fmtA("convergedRejected", { v, n, f }));
    for (const [f, text] of lastReview.blocks) {
      const hit = gating.find((probe) => new RegExp(`(?<![\\w.])${probe.replace(".", "\\.")}(?![\\w.])`).test(text));
      if (hit) problems.push(fmtA("convergedGating", { v, n, f, p: hit }));
    }
    const bounded = validDate(fm.baselined) && lastReview.date <= fm.baselined; // this review stands for approve
    const note = plan.notes.find((x) => x.text === `converged after round ${n} — ${k} findings applied, none gating`
      && x.date >= lastReview.date && (!bounded || x.date <= fm.baselined));
    if (!note) problems.push(fmtA("convergedNote", { v, n, k, date: lastReview.date }));
    if (lastReview.reviewer !== reviewM[1]) problems.push(fmtA("convergedReviewer", { v, n, by: lastReview.reviewer }));
    if (problems.length === before) converged = lastReview;
  }
  // wherever a latest READY review is required, a converged review is that record
  const approvals = converged ? [...readyReviews, converged] : readyReviews;
  if ((status === "ready" || status === "done") && review === "pending") problems.push(`status ${status} but review is pending`);
  if (past && review !== "pending") {
    if (!approvals.length && !convAttempted) problems.push(`review is ${review} but ${plan.slug}.reviews.md has no VERDICT: READY`);
    else if (!converged && !convAttempted && lastReady) {
      // the review on record is the LATEST one — a later REVISE cancels an earlier READY
      if (lastReview.verdict !== "READY") problems.push(`review is ${review} but the latest review (Review ${lastReview.n}) is ${lastReview.verdict ?? "without a verdict"} — set review: pending until a later READY`);
      if (lastReady.reviewer !== (reviewM?.[1] ?? review)) problems.push(`review: ${review} but the latest READY review (Review ${lastReady.n}) was by ${lastReady.reviewer}`);
      if (lastReady.coverage && fm.coverage_reviewer !== lastReady.coverage) problems.push(`coverage_reviewer "${fm.coverage_reviewer}" ≠ Review ${lastReady.n}'s line "${lastReady.coverage}"`);
      // plan-accuracy A2: after a later READY re-review moved `review:` to that reviewer, the converged approval on
      // record (convergedOnRecord) still stands for the baseline date
      if (fm.baselined !== "none" && validDate(fm.baselined) && !readyReviews.some((r) => r.date <= fm.baselined) && !convergedOnRecord(plan)) problems.push(`no READY review dated on/before the baseline date ${fm.baselined}`);
    }
  }
  if (status === "in-progress" && review === "pending") warnings.push("review is pending (re-opened by an amendment?) — approve before close");
  if (lastMaterialReviewTrigger && !approvals.some((r) => r.date >= lastMaterialReviewTrigger.date)) {
    const a = lastMaterialReviewTrigger;
    if (status === "done") problems.push(`${a.id} (${gating.includes(a.layer) ? `gating probe ${a.layer}` : "removes a baseline item"}) has no READY review dated on/after it`);
    else if (review !== "pending") problems.push(`${a.id} (${gating.includes(a.layer) ? `gating probe ${a.layer}` : "removes a baseline item"}) requires review: pending until re-approved`);
  }

  // 5. done: everything verified, report present; epics: ≥1 child, all done
  if (status === "done") {
    const open = plan.items.filter((it) => !it.checked || !verified.has(it.id)).map((it) => it.id);
    if (open.length) problems.push(`status done but unverified items: ${open.join(", ")}`);
    if (!(plan.sections["Report"] ?? []).some((l) => l.trim())) problems.push("status done but ## Report is empty");
  }
  // hierarchy: any plan may have children and any plan may be a parent (v0.2); the tree must exist, be reciprocal and acyclic
  if (fm.size === "Epic" && !plan.children.length) problems.push("Epic with no children under ## Children");
  const epicDone = fm.size === "Epic" && status === "done";
  for (const c of plan.children) {
    const child = store.bySlug.get(c.slug);
    if (!child) { (epicDone ? problems : warnings).push(`child ${c.slug} has no plan file`); continue; }
    if (epicDone) {
      // each child is verified on its own: parent field, status, and its own check (guarded against a cycle)
      if (child.fm.parent !== plan.slug) problems.push(`child ${c.slug} has parent ${child.fm.parent ?? "none"}, not ${plan.slug}`);
      if (child.fm.status !== "done") problems.push(`child ${c.slug} is ${child.fm.status}, not done`);
      if (!store.checking.has(c.slug)) {
        store.checking.add(plan.slug);
        try { const n = checkPlan(child, all).problems.length; if (n) problems.push(`child ${c.slug} has ${n} check problem(s)`); } finally { store.checking.delete(plan.slug); }
      }
    }
    const actual = child.fm.status === "done" ? "done" : child.fm.status === "in-progress" ? "in-progress" : "planned";
    if (actual !== c.status) warnings.push(`child ${c.slug} manifest says ${c.status}, plan says ${child.fm.status}`);
  }
  if (store.cycles.has(plan.slug)) problems.push(`parent cycle: ${store.cycles.get(plan.slug)}`);
  else if (fm.parent && fm.parent !== "none") {
    const parent = store.bySlug.get(fm.parent);
    if (!parent) problems.push(`parent ${fm.parent} not found in the store`);
    else if (!parent.children.some((c) => c.slug === plan.slug)) problems.push(`parent ${fm.parent} does not list ${plan.slug} under ## Children`);
  }

  // 6. lifecycle replay
  let prev = null, prevDate = "";
  for (const t of plan.transitions) {
    if (!validDate(t.date)) problems.push(`transition to ${t.status}: date "${t.date}" is not valid`);
    else if (t.date < prevDate) problems.push(`transition to ${t.status} on ${t.date} is dated before the previous transition`);
    prevDate = t.date > prevDate ? t.date : prevDate;
    const from = LEGAL[t.status];
    if (!from) { problems.push(`unknown transition target "${t.status}"`); prev = t.status; continue; }
    if (!from.includes(prev)) problems.push(`illegal transition ${prev ?? "(start)"} → ${t.status}`);
    if (t.status === "in-progress" && prev === "done") {
      const m = t.detail.match(CMD.reopen);
      const a = m && plan.amendments.find((x) => x.id === m[1]);
      if (!m) problems.push("reopen must cite its amendment: `status → in-progress · reopen A<n>`");
      else if (!a) problems.push(`reopen cites ${m[1]}, which does not exist`);
      else if (a.date > t.date) problems.push(`reopen cites ${m[1]}, dated after the reopen`);
    } else if (t.status === "in-progress") {
      if (!CMD.start.test(t.detail)) problems.push("ready → in-progress must read `status → in-progress · start`");
    } else if (t.status === "cancelled") {
      if (!CMD.cancelled.test(t.detail)) problems.push("cancelled transition must read `status → cancelled · cancel · <reason>`");
    } else if (t.status === "superseded") {
      const m = t.detail.match(CMD.superseded);
      if (!m) problems.push("superseded transition must read `status → superseded · supersede · by <slug>`");
      else if (!all.find((p) => p.slug === m[1])) problems.push(`superseded by ${m[1]}, which is not in the store`);
    } else if (CMD[t.status] && !CMD[t.status].test(t.detail)) problems.push(`transition to ${t.status} must read \`status → ${t.status} · ${t.status === "draft" ? "plan" : t.status === "ready" ? "approve" : "close"}\``);
    prev = t.status;
  }
  const reachedReady = plan.transitions.some((t) => t.status === "ready");
  if (!plan.transitions.length) problems.push("no status transition in ## Log");
  else if (prev !== status) problems.push(`frontmatter status "${status}" ≠ last Log transition "${prev}"`);
  // baselined follows history, not the current state: a cancelled plan that was once ready keeps its baseline (B3)
  const shouldHaveBaseline = past || reachedReady;
  if (shouldHaveBaseline && (fm.baselined ?? "none") === "none") problems.push(`status ${status} but baselined is none${past ? "" : " (the plan reached ready; the baseline is never removed)"}`);
  if (!shouldHaveBaseline && fm.baselined && fm.baselined !== "none") problems.push(`status ${status} but baselined is set — the plan never reached ready`);
  if (TERMINAL.includes(status) && (fm.closed ?? "none") === "none") problems.push(`status ${status} but closed is none`);
  if (!TERMINAL.includes(status) && fm.closed && fm.closed !== "none") problems.push(`status ${status} but closed is set`);

  // 7. decision-required assumptions block anything past draft
  const dr = plan.assumptions.filter((a) => a.type === "decision-required").length;
  if (dr && status !== "draft") problems.push(`${dr} decision-required assumption(s) while status is ${status}`);

  // 8. work packages (wbs-view D15–D17)
  const wbs = packageCheck(plan);
  problems.push(...wbs.problems);
  warnings.push(...wbs.warnings);

  return { problems, warnings, verified: verified.size, preVerified: preVerified.size, total: plan.items.length, report: reportNumbers(plan, discoveredOps, wbs.grew) };
}

export function reportNumbers(plan, discoveredOps, grew = null) {
  const B = plan.baseline.length;
  const kinds = { discovered: 0, corrected: 0, requested: 0, emergent: 0, defect: 0, external: 0 };
  const missed = {};
  const counted = (a) => a.kind === "discovered" || a.kind === "corrected";
  let wrong = 0, missedOps = 0;
  for (const a of plan.amendments) {
    kinds[a.kind]++;
    if (!counted(a)) continue;
    missed[a.layer] = (missed[a.layer] ?? 0) + 1;
    // the split is of the discovered amendments' design changes; corrected is reported as its own number
    if (a.kind !== "discovered") continue;
    // wrong = the plan had the item and got it wrong (~Dn); missed = it had no item at all (+Dn, or no ops)
    const design = a.ops.filter((o) => /^[+~]/.test(o));
    if (!design.length) missedOps += 1;
    for (const o of design) if (o.startsWith("~")) wrong++; else missedOps++;
  }
  // discovered counts design changes (+/~ ops on D-items), so bundling several into one amendment does not lower it
  const G = discoveredOps ?? plan.amendments.filter(counted).reduce((n, a) => n + Math.max(1, a.ops.filter((o) => /^[+~]/.test(o)).length), 0);
  const rate = B ? Math.round((B / (B + G)) * 100) : null;
  // `grew` is the per-package growth of D17 when the caller has run the package checks; a plan with no
  // `## Work breakdown` section has no growth line at all, which is why null and [] are different answers
  return { baseline: B, discoveredDesign: G, wrong, missedOps, ...kinds, rate, missed, grew: grew ?? (plan.hasWbs ? packageCheck(plan).grew : null) };
}

// ---------------------------------------------------------------- atomic writes

// Every file the script writes goes through here: a temp file beside the target, then a rename, so a reader never
// sees half a file. With `expect` (the bytes the caller read), the write is refused — returns false — when the file
// no longer holds them; the caller re-reads and recomputes. The guarantee is exact: an edit that lands before the
// final comparison is never lost; one inside the window between that comparison and the rename can be (no lock is
// taken — the epic rejected locks), and git or a backup is the recovery. A temp file left by a crashed writer whose
// process is gone is swept on the next call. DOD_FAULT=before-rename / after-compare exist for the selftest only.
const TEMP_RE = (name) => new RegExp(`^${name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\.(\\d+)\\.[0-9a-f]{8}\\.tmp$`);
const alive = (pid) => { if (pid === process.pid) return false; try { process.kill(pid, 0); return true; } catch (e) { return e.code === "EPERM"; } };
export function writeAtomic(path, text, { expect, faults = true } = {}) {
  const dir = dirname(path), name = basename(path);
  try { for (const f of readdirSync(dir)) { const m = f.match(TEMP_RE(name)); if (m && !alive(Number(m[1]))) rmSync(join(dir, f), { force: true }); } } catch { /* directory unreadable: the write below reports it */ }
  const tmp = join(dir, `${name}.${process.pid}.${randomBytes(4).toString("hex")}.tmp`);
  writeFileSync(tmp, text, { flag: "wx" }); // exclusive: never follows or reuses an entry planted at the temp name
  const fault = faults ? process.env.DOD_FAULT : undefined; // the backup append opts out: the hooks target the plan
  if (fault === "before-rename") { const e = new Error(`DOD_FAULT=before-rename: ${name} not renamed`); e.code = "EDODFAULT"; throw e; }
  try {
    if (expect !== undefined) {
      // selftest hooks: an edit that lands before the final comparison — once, or on every attempt
      const EDIT = "- edit landed before the final comparison\n";
      if (fault === "before-compare-once" && !readFileSync(path, "utf8").includes(EDIT)) appendFileSync(path, EDIT);
      if (fault === "every-compare") appendFileSync(path, EDIT);
      let cur = null;
      try { cur = readFileSync(path, "utf8"); } catch (e) { if (e.code !== "ENOENT") throw e; }
      if (cur !== expect) { rmSync(tmp, { force: true }); return false; }
      if (fault === "after-compare") appendFileSync(path, "- edit landed after the final comparison\n");
    }
    // selftest hook: after every check, swap the target for a symlink to a file outside the store — the rename
    // below must replace the link itself, never write through it
    const swap = fault === "before-rename-swap" ? process.env.DOD_FAULT_SWAP_TARGET : undefined;
    if (swap) { rmSync(path, { force: true }); symlinkSync(swap, path); }
    for (let k = 0; ; k++) {
      try { renameSync(tmp, path); return true; }
      catch (e) { if (k >= 20 || !["EPERM", "EBUSY", "EACCES"].includes(e.code)) throw e; const t = Date.now() + 25; while (Date.now() < t) { /* Windows: target briefly open elsewhere */ } }
    }
  } catch (e) { rmSync(tmp, { force: true }); throw e; }
}

